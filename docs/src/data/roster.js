/** Specials + super, for the move list shown on the select screen. */
export function signatureMoves(char) {
  return Object.entries(char.moves)
    .filter(([, m]) => m.tier === 'special' || m.tier === 'super')
    .map(([id, m]) => ({ id, ...m }));
}
