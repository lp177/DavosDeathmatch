/* ══════════════════════════════════════════════════════════════
   The roster.

   Eight delegates. Every special move is drawn from something the
   figure actually said or did — the joke only works if the source is
   recognisable. This is political satire aimed at public figures in
   their public capacity.

   Each entry provides:
     stats  — health / speed / jump, used by the simulation
     look   — parameters the procedural caricature renderer draws from
     moves  — twelve standard normals plus specials and one super
     order  — move-matching priority, generated by finalise()
   ══════════════════════════════════════════════════════════════ */

import { IN, HIT } from '../sim/constants.js';
import { move, box, standardNormals } from './movekit.js';

/* Motion complexity decides move-matching priority: the fanciest input
   that the player actually performed should win. */
const COMPLEXITY = {
  qcfx2: 9, qcbx2: 9, hcf: 7, hcb: 7, dp: 6, rdp: 6,
  charge_bf: 5, charge_du: 5, dd: 4, qcf: 3, qcb: 3, none: 0,
};
const TIER_RANK = { super: 0, special: 1, command: 2, normal: 3 };

function finalise(char) {
  char.order = Object.keys(char.moves).sort((a, b) => {
    const ma = char.moves[a], mb = char.moves[b];
    const ta = TIER_RANK[ma.tier] ?? 3, tb = TIER_RANK[mb.tier] ?? 3;
    if (ta !== tb) return ta - tb;
    const ca = COMPLEXITY[ma.input?.motion ?? 'none'] ?? 0;
    const cb = COMPLEXITY[mb.input?.motion ?? 'none'] ?? 0;
    if (ca !== cb) return cb - ca;
    // Stable tie-break so both peers build identical order arrays.
    return a < b ? -1 : a > b ? 1 : 0;
  });
  return char;
}

