/* ══════════════════════════════════════════════════════════════
   Service worker — offline play, and an end to stale reloads.

   GENERATED by tools/make-sw.js. Edit tools/sw-template.js instead.

   Strategy: cache first, revalidate always.

   The whole game is 35 files and well under a megabyte, so it is all
   precached on install. Every request is then answered from that cache —
   instant, and it works with no network at all — while a background fetch
   refreshes the entry for next time.

   The stale-reload problem this replaces was not really a caching bug, it
   was a *notification* bug: the browser held an old copy and nothing ever
   said so. Here a new deployment produces a new worker, which installs
   beside the running one and waits. The page is told, shows a banner, and
   swaps over only when the player agrees — so a version never changes
   underneath a match in progress, and half the modules can never come from
   one build with the rest from another.
   ══════════════════════════════════════════════════════════════ */

const VERSION = '__VERSION__';
const CACHE = `davos-${VERSION}`;
const PRECACHE = __PRECACHE__;

/* Requests that must always go to the network.
   The relay credentials at /ice expire within hours and are minted per
   request — a cached copy is worse than none, because it fails at ICE time
   with no explanation. */
const ALWAYS_LIVE = /\/(ice|signal)(\/|$|\?)/;

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    // Bypass the HTTP cache while precaching, or a stale intermediary can
    // seed the new version with the old files it was meant to replace.
    await cache.addAll(PRECACHE.map((p) => new Request(p, { cache: 'reload' })));
    // Deliberately NOT skipWaiting(). The page decides when to switch.
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys
      .filter((k) => k.startsWith('davos-') && k !== CACHE)
      .map((k) => caches.delete(k)));
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;

  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;   // signalling, TURN, trackers
  if (ALWAYS_LIVE.test(url.pathname)) return;

  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const hit = await cache.match(req);

    const fromNetwork = fetch(req).then((res) => {
      // Opaque and error responses must never replace a good cached copy.
      if (res && res.ok && res.type === 'basic') cache.put(req, res.clone());
      return res;
    }).catch(() => null);

    if (hit) {
      event.waitUntil(fromNetwork);      // refresh for next time, don't wait
      return hit;
    }

    const res = await fromNetwork;
    if (res) return res;

    // Offline and never seen: a navigation can still open the game shell.
    if (req.mode === 'navigate') {
      const shell = await cache.match('./');
      if (shell) return shell;
    }
    return new Response('Offline, and this is not in the cache.',
      { status: 503, headers: { 'Content-Type': 'text/plain' } });
  })());
});

self.addEventListener('message', (event) => {
  if (event.data === 'apply-update') self.skipWaiting();
  if (event.data === 'version') {
    event.source?.postMessage({ type: 'version', version: VERSION });
  }
});
